"""SYNTHETIC CASAS-format smart-home data generator.

!!! SYNTHETIC. Generated by code, not collected from real homes. Metrics computed on it demonstrate that the
pipeline works end to end; they are NOT evidence of accuracy on the real CASAS dataset. !!!

The generator is fixed (not tuned to any model score): per-home sensor layouts with home-specific numbering,
per-home habit shifts and event-rate multipliers, spurious sensor noise, overlapping sensors between activities,
and imperfect labels (episode boundaries blur because windows span activity changes).
"""
from __future__ import annotations
import math
from datetime import datetime, timedelta
from pathlib import Path

import numpy as np

ACTIVITIES = ["Sleeping", "Bed_to_Toilet", "Meal_Preparation", "Eating", "Relax", "Leave_Home", "Enter_Home", "Housekeeping"]

# zone -> (n motion, n door, n temp)
ZONES = {"bedroom": (2, 0, 0), "bathroom": (1, 1, 0), "kitchen": (3, 2, 1), "living": (3, 0, 0),
         "dining": (1, 0, 0), "entrance": (1, 1, 0), "office": (1, 0, 0)}

# activity -> dict(zones weights, mean gap seconds, n events range, hour weights fn)
def _hour_w(hours: dict[tuple[int, int], float], base: float = 0.02):
    def f(h: float) -> float:
        for (a, b), w in hours.items():
            if (a <= b and a <= h < b) or (a > b and (h >= a or h < b)):
                return w
        return base
    return f

SPEC = {
    "Sleeping": dict(zones={"bedroom": 0.9, "bathroom": 0.05, "living": 0.05}, gap=420, n=(6, 40), hw=_hour_w({(22, 7): 1.0, (13, 15): 0.08})),
    "Bed_to_Toilet": dict(zones={"bedroom": 0.45, "bathroom": 0.5, "living": 0.05}, gap=18, n=(5, 12), hw=_hour_w({(23, 6): 0.35})),
    "Meal_Preparation": dict(zones={"kitchen": 0.8, "dining": 0.08, "living": 0.12}, gap=14, n=(25, 110), hw=_hour_w({(6, 9): 0.5, (11, 14): 0.5, (17, 20): 0.6})),
    "Eating": dict(zones={"dining": 0.45, "kitchen": 0.45, "living": 0.1}, gap=55, n=(8, 25), hw=_hour_w({(7, 10): 0.4, (12, 14): 0.4, (18, 21): 0.5})),
    "Relax": dict(zones={"living": 0.8, "office": 0.1, "dining": 0.1}, gap=85, n=(12, 90), hw=_hour_w({(9, 23): 0.5})),
    "Leave_Home": dict(zones={"entrance": 1.0}, gap=6, n=(3, 6), hw=_hour_w({(7, 10): 0.3, (12, 19): 0.2})),
    "Enter_Home": dict(zones={"entrance": 0.6, "living": 0.2, "kitchen": 0.2}, gap=7, n=(3, 7), hw=_hour_w({(12, 22): 0.2})),
    "Housekeeping": dict(zones={z: 1 for z in ZONES} , gap=11, n=(30, 100), hw=_hour_w({(9, 17): 0.25})),
}


def _layout(rng: np.random.Generator) -> dict:
    counters = {"M": 0, "D": 0, "T": 0}
    ids = {k: list(rng.permutation(40)[:30] + 1) for k in counters}  # home-specific numbering
    lay = {}
    for zone, (m, d, t) in ZONES.items():
        m, d = max(1, m + int(rng.integers(-1, 2)) if m else 0), d
        sensors = []
        for kind, k in (("M", m), ("D", d), ("T", t)):
            for _ in range(k):
                sensors.append((f"{kind}{ids[kind][counters[kind]]:03d}", kind))
                counters[kind] += 1
        lay[zone] = sensors
    return lay


def _emit(rng, layout, act, home_rate, all_sensors, t0, n, noise=0.08):
    spec = SPEC[act]
    zones, w = list(spec["zones"]), np.array(list(spec["zones"].values()), float)
    w /= w.sum()
    out, t = [], t0
    zone = rng.choice(zones, p=w)
    for i in range(n):
        if rng.random() < 0.55:
            zone = rng.choice(zones, p=w)
        sens = layout[zone]
        if act == "Leave_Home":
            door = [s for s in layout["entrance"] if s[1] == "D"]
            s = door[0] if i in (0, n - 1) else layout["entrance"][0]
        elif act == "Enter_Home":
            door = [s for s in layout["entrance"] if s[1] == "D"]
            s = door[0] if i in (0, 2) else sens[int(rng.integers(len(sens)))]
        elif act == "Meal_Preparation" and rng.random() < 0.25:
            pool = [x for x in layout["kitchen"] if x[1] in "DT"] or sens
            s = pool[int(rng.integers(len(pool)))]
        else:
            s = sens[int(rng.integers(len(sens)))]
        if rng.random() < noise:
            s = all_sensors[int(rng.integers(len(all_sensors)))]
        kind = s[1]
        msg = ("ON" if rng.random() < 0.55 else "OFF") if kind == "M" else ("OPEN" if rng.random() < 0.5 else "CLOSE") if kind == "D" else f"{rng.normal(22, 2):.1f}"
        out.append((t, s[0], msg, act))
        t = t + timedelta(seconds=float(rng.exponential(spec["gap"] * home_rate)) + 0.5)
    return out, t


def generate_home(seed: int, days: int = 28, start: datetime = datetime(2023, 3, 1)) -> list[tuple]:
    rng = np.random.default_rng(seed)
    layout = _layout(rng)
    all_sensors = [s for z in layout.values() for s in z]
    rate = float(np.exp(rng.normal(0, 0.25)))
    shift = float(rng.normal(0, 1.0))  # habit shift in hours
    rows, t = [], start
    end = start + timedelta(days=days)
    prev = None
    while t < end:
        h = (t.hour + t.minute / 60 - shift) % 24
        if prev == "Leave_Home":
            t += timedelta(hours=float(rng.uniform(1, 8)))
            act = "Enter_Home"
        else:
            wts = np.array([SPEC[a]["hw"](h) for a in ACTIVITIES])
            if prev:
                wts[ACTIVITIES.index(prev)] *= 0.4
            if prev == "Meal_Preparation":
                wts[ACTIVITIES.index("Eating")] *= 6
            act = ACTIVITIES[int(rng.choice(len(ACTIVITIES), p=wts / wts.sum()))]
        n = int(rng.integers(*SPEC[act]["n"]))
        ev, t = _emit(rng, layout, act, rate, all_sensors, t, n)
        rows += ev
        prev = act
        t += timedelta(minutes=float(rng.exponential(25)))
    return rows


def write_dataset(out_dir: str | Path, n_homes: int = 12, base_seed: int = 20231022, days: int = 28) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = []
    for i in range(n_homes):
        rows = generate_home(base_seed + i, days)
        p = out / f"synthetic_home{i+1:02d}.txt"
        lines = ["# SYNTHETIC CASAS-format data generated by switch_p3c.casas.synthetic — NOT real CASAS"]
        begin_end = i % 4 == 3  # exercise the begin/end annotation style on some homes
        for j, (ts, s, m, a) in enumerate(rows):
            lab = a
            if begin_end:
                first = j == 0 or rows[j - 1][3] != a
                last = j == len(rows) - 1 or rows[j + 1][3] != a
                lab = f"{a} begin" if first else (f"{a} end" if last else "")
            lines.append(f"{ts.strftime('%Y-%m-%d %H:%M:%S.%f')[:-3]}\t{s}\t{m}\t{lab}".rstrip("\t"))
        p.write_text("\n".join(lines) + "\n")
        paths.append(p)
    return paths
