"""Deterministic home simulator. Pure: no I/O, no wall clock, no randomness.

EVENT ORDERING CONTRACT
  Queue key = (sim_minute, class_rank, seq)
    class_rank 0 = scenario events  (assigned seq in order of (at, declared index))
    class_rank 1 = time triggers     (one event per distinct minute)
    class_rank 2 = state-change triggers (generated by state changes, same minute)
  seq is a monotonic counter, so the key is a total order.
  Routines matched by one event run in ascending (priority, routine_id); a
  routine matched by several triggers runs once. Actions run in declared order.
  Later writer wins; contradictory writes are recorded in `conflicts`.
  Unknown (null) state in a condition => the action is NOT executed and is
  recorded as `indeterminate`.
"""
import copy, hashlib, heapq, json
from typing import Any, Optional
from .catalog import CATALOG
from .schemas import Routine, Scenario, Condition
from .validation import hhmm_to_min, min_to_hhmm

SIMULATOR_VERSION = "1.0.0"
MAX_EVENTS = 1000


def canonical(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), default=str)


def sha(obj: Any) -> str:
    return hashlib.sha256(canonical(obj).encode()).hexdigest()


def cond_expr(c: Condition) -> str:
    if c.op == "time_between":
        return f"time in [{c.start},{c.end})"
    return f"{c.device}.{c.attr} {'==' if c.op == 'eq' else '!='} {c.value!r}"


def eval_condition(c: Condition, state: dict, minute: int) -> tuple[Optional[bool], Any]:
    """Three-valued: True / False / None(unknown). Strict type+value equality."""
    if c.op == "time_between":
        s, e = hhmm_to_min(c.start), hhmm_to_min(c.end)
        return ((s <= minute < e) if s <= e else (minute >= s or minute < e)), min_to_hhmm(minute)
    if c.op not in ("eq", "neq"):
        return None, None                      # unsupported operator: UNKNOWN, never silently treated as neq
    actual = state.get(c.device, {}).get(c.attr)
    if actual is None:
        return None, None
    same = type(actual) is type(c.value) and actual == c.value
    return (same if c.op == "eq" else not same), actual


def eval_all(items: list[tuple[str, Condition]], state: dict, minute: int):
    recs, any_false, any_unknown = [], False, False
    for scope, c in items:
        r, actual = eval_condition(c, state, minute)
        recs.append({"scope": scope, "expr": cond_expr(c), "actual": actual, "result": r})
        any_false |= r is False
        any_unknown |= r is None
    return (False if any_false else (None if any_unknown else True)), recs


def simulate(routines: list[Routine], scenario: Scenario, max_events: int = MAX_EVENTS) -> dict:
    active = sorted([r for r in routines if r.enabled], key=lambda r: (r.priority, r.routine_id))
    state = {d: {a: scenario.initial_state.get(d, {}).get(a) for a in spec["attrs"]} for d, spec in CATALOG.items()}
    initial = copy.deepcopy(state)
    lo, hi = hhmm_to_min(scenario.start), hhmm_to_min(scenario.end)
    heap: list = []
    seq = 0

    def push(minute, rank, ev):
        nonlocal seq
        seq += 1
        heapq.heappush(heap, (minute, rank, seq, ev))

    for idx, e in sorted(enumerate(scenario.events), key=lambda x: (hhmm_to_min(x[1].at), x[0])):
        push(hhmm_to_min(e.at), 0, {"kind": e.kind, "src": e.event_id, "name": e.name,
                                    "device": e.device, "attr": e.attr, "value": e.value})
    for m in sorted({hhmm_to_min(t.at) for r in active for t in r.triggers if t.type == "time"}):
        if lo <= m <= hi:
            push(m, 1, {"kind": "time", "src": f"time@{min_to_hhmm(m)}"})

    trace: list[dict] = []
    conflicts: list[dict] = []
    flags = {"indeterminate": False, "complete": True, "error": None}

    def add(**kw) -> str:
        eid = f"E{len(trace) + 1:04d}"
        trace.append({"event_id": eid, "seq": len(trace) + 1, **kw})
        return eid

    processed = 0
    while heap:
        minute, rank, _, ev = heapq.heappop(heap)
        processed += 1
        if processed > max_events:
            flags.update(complete=False, error=f"event limit {max_events} exceeded (possible trigger loop)")
            break
        t = min_to_hhmm(minute)
        matched: list[Routine] = []
        if ev["kind"] == "set":
            before = copy.deepcopy(state)
            prev = state[ev["device"]][ev["attr"]]
            state[ev["device"]][ev["attr"]] = ev["value"]
            src = add(type="external_event", sim_time=t, kind="set", source=ev["src"], device=ev["device"], attr=ev["attr"],
                      previous=prev, resulting=ev["value"], changed=prev != ev["value"], state_before=before)
            if prev != ev["value"]:
                push(minute, 2, {"kind": "state_change", "src": src, "device": ev["device"], "attr": ev["attr"], "value": ev["value"]})
        elif ev["kind"] == "fire":
            src = add(type="external_event", sim_time=t, kind="fire", source=ev["src"], name=ev["name"], state_before=copy.deepcopy(state))
            matched = [r for r in active if any(x.type == "event" and x.name == ev["name"] for x in r.triggers)]
        elif ev["kind"] == "time":
            src = add(type="clock_tick", sim_time=t, kind="time", source=ev["src"], state_before=copy.deepcopy(state))
            matched = [r for r in active if any(x.type == "time" and hhmm_to_min(x.at) == minute for x in r.triggers)]
        else:  # state_change
            src = ev["src"]
            matched = [r for r in active if any(x.type == "state" and x.device == ev["device"] and x.attr == ev["attr"]
                                                and type(x.value) is type(ev["value"]) and x.value == ev["value"] for x in r.triggers)]
        writes: dict = {}
        for r in matched:
            add(type="routine_fired", sim_time=t, routine_id=r.routine_id, routine_version=r.version,
                source_event=src, state_before=copy.deepcopy(state))
            for a in r.actions:
                items = [("routine", c) for c in r.conditions] + [("action", c) for c in a.conditions]
                res, recs = eval_all(items, state, minute)
                before = copy.deepcopy(state)
                prev = state[a.device][a.attr]
                base = dict(type="action", sim_time=t, routine_id=r.routine_id, routine_version=r.version, source_event=src,
                            action_id=a.action_id, device=a.device, attr=a.attr, target_value=a.value,
                            previous=prev, conditions=recs, state_before=before)
                if res is True:
                    state[a.device][a.attr] = a.value
                    changed = prev != a.value
                    eid = add(**base, resulting=a.value, changed=changed, outcome="executed")
                    if changed:
                        push(minute, 2, {"kind": "state_change", "src": eid, "device": a.device, "attr": a.attr, "value": a.value})
                    w = writes.setdefault((a.device, a.attr), [])
                    w.append((eid, a.value))
                elif res is False:
                    add(**base, resulting=prev, changed=False, outcome="skipped")
                else:
                    flags["indeterminate"] = True
                    add(**base, resulting=prev, changed=False, outcome="indeterminate")
        for (d, at), ws in writes.items():
            if len({repr(v) for _, v in ws}) > 1:
                conflicts.append({"device": d, "attr": at, "source_event": src, "writes": [e for e, _ in ws],
                                  "winner": ws[-1][0], "final_value": ws[-1][1]})
    out = {"simulator_version": SIMULATOR_VERSION, "scenario_id": scenario.scenario_id, "scenario_version": scenario.version,
           "seed": scenario.seed,
           "window": {"start": scenario.start, "end": scenario.end, "start_min": lo, "end_min": hi}, "initial_state": initial, "final_state": state, "trace": trace, "conflicts": conflicts, **flags}
    out["result_hash"] = sha({k: out[k] for k in ("initial_state", "final_state", "trace", "conflicts", "complete", "indeterminate")})
    return out
