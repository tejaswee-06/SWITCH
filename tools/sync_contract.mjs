// Regenerates src/contracts/canonicalHome.js from contracts/canonical_home.json (the shared room/device contract).
// tests/canonical.test.mjs fails if the two drift apart.   Usage: node tools/sync_contract.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const src = new URL('../contracts/canonical_home.json', import.meta.url);
const dst = new URL('../src/contracts/canonicalHome.js', import.meta.url);
const json = JSON.parse(readFileSync(src, 'utf8'));
writeFileSync(dst, `// GENERATED by tools/sync_contract.mjs from contracts/canonical_home.json. Do not edit by hand.\nexport const CANONICAL_HOME = ${JSON.stringify(json, null, 1)};\n`);
console.log('wrote', dst.pathname);
